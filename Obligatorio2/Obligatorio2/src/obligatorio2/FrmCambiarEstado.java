    private void lstMascotasValueChanged(javax.swing.event.ListSelectionEvent evt) {//GEN-FIRST:event_lstMascotasValueChanged
        if (!evt.getValueIsAdjusting()){
            habilitarOpciones();
            Mascota seleccionada = lstMascotas.getSelectedValue();
            
            if (seleccionada != null){
                if (seleccionada.getEstado() == EstadoMascota.DISPONIBLE){
                    this.rbtnDisponible.setSelected(true);
                } else {
                    this.rbtnNoDisponible.setSelected(true);
                }
            } 
        }
    }//GEN-LAST:event_lstMascotasValueChanged

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        Mascota m = this.lstMascotas.getSelectedValue();
        
        if (this.rbtnDisponible.isSelected()){
            m.setEstado(EstadoMascota.DISPONIBLE);
        } else if (this.rbtnNoDisponible.isSelected()){
            m.setEstado(EstadoMascota.NO_DISPONIBLE);
        }
        JOptionPane.showMessageDialog(this, m.getNombre() + " cambió su estado a: " + m.getEstado().toString());
        cargarLista();
        deshabilitarOpciones();

    }//GEN-LAST:event_btnGuardarActionPerformed

    

